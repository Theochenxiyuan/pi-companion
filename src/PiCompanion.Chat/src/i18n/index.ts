const currentLocale = ref<AppLocale>('zh-CN')

export function setLocale(value: string | null | undefined) {
  currentLocale.value = value === 'en-US' ? 'en-US' : 'zh-CN'
  document.documentElement.lang = currentLocale.value
}

export function useI18n() {
  const locale = computed(() => currentLocale.value)
  return { locale, setLocale, t }
}

export function t(source: string, parameters: TranslationParameters = {}) {
  const template = currentLocale.value === 'en-US' ? english[source] ?? source : chinese[source] ?? source
  return template.replace(/\{([^}]+)\}/gu, (_, name: string) => String(parameters[name] ?? `{${name}}`))
}

export function localeCode() {
  return currentLocale.value
}
